#: What the entry point says about itself, transcribed from the real one. A symlink, and the
#: traversal question is about where it leads.
SHEBANG = "#!/opt/encore/venv/bin/python\nimport sys\n"

#: Where that leads on the machine from the issue report. `namei` said the quiet part: the walk stops
#: at `/root`, which is `drwx------` on Debian by default.
BROKEN_INTERPRETER = "/root/.local/share/uv/python/cpython-3.12/bin/python3.12"

#: Where it leads on a machine installed by the installer on this branch.
FIXED_INTERPRETER = "/opt/encore/python/cpython-3.12/bin/python3.12"

#: The lockfile and the stamp agreeing, so "the environment is current" is true in the one sense the
#: installer already knew how to ask about. #46's whole shape: correct, and irrelevant.
LOCK = "lockfile bytes\n"

PRODUCTION = Layout()

#: What the four rendered files say on this machine, generated by the same functions the installer
#: writes with — the arrangement `test_installer_plan.py` uses for the same reason: change what a
#: generated unit file says and this machine stops being "already installed", instead of the test
#: quietly agreeing with whatever the code happens to do.
_CONFIG = EncoreConfig()
_RENDERED: dict[str, str] = {
    PRODUCTION.config_file: config_text(_CONFIG, PRODUCTION),
    PRODUCTION.environment_file: environment_text(admin_password=None, layout=PRODUCTION),
    PRODUCTION.unit_file: unit_text(
        _CONFIG,
        PRODUCTION,
        application=Path(PRODUCTION.application),
        venv=Path(PRODUCTION.venv),
        config_path=Path(PRODUCTION.config_file),
    ),
    PRODUCTION.tmpfiles_file: tmpfiles_text(PRODUCTION),
}


def modes(*, fixed: bool = False) -> dict[str, tuple[str, str, int]]:
    """The modes of an installed appliance, at the paths `layout.py` says it uses.

    Derived from the layout table rather than retyped, because the claim here is not "these are the
    documented modes" — `test_installer_layout.py` has that — but "a machine that is right in every
    way the installer already knows how to ask about is still broken". The one `0700` in the result
    is `/root`, a directory the installer never created, never mode-changed and never mentioned, and
    which is why the report came out green: every other answer is correct about the file it was
    asked of.
    """

    found = {
        "/": ("root", "root", 0o755),
        "/opt": ("root", "root", 0o755),
        "/etc": ("root", "root", 0o755),
    }
    # Two loops rather than one over a starred union: `Directory` and `ManagedFile` are different
    # dataclasses, and the point of reading them off the table is that this file states no modes of
    # its own.
    for directory in PRODUCTION.directories:
        found[directory.final] = (directory.owner, directory.group, directory.mode)
        for parent in _parents(directory.final):
            found.setdefault(parent, ("root", "root", 0o755))
    for managed in PRODUCTION.files:
        found[managed.final] = (managed.owner, managed.group, managed.mode)
        for parent in _parents(managed.final):
            found.setdefault(parent, ("root", "root", 0o755))
    # The code and the environment, which are directories in 13.3 and whose contents this machine
    # answers from `read()` below rather than from a disk.
    found["/opt/encore/application/encore/__init__.py"] = ("root", "encore", 0o644)
    found["/opt/encore/application/pyproject.toml"] = ("root", "encore", 0o644)
    found["/opt/encore/application/uv.lock"] = ("root", "encore", 0o644)
    found["/opt/encore/venv/bin"] = ("root", "encore", 0o755)
    found["/opt/encore/venv/bin/encore-server"] = ("root", "encore", 0o755)
    found["/opt/encore/venv/.encore-lock"] = ("root", "encore", 0o644)
    interpreter = FIXED_INTERPRETER if fixed else BROKEN_INTERPRETER
    for parent in _parents(interpreter):
        found[parent] = (
            ("root", "root", 0o755) if parent.startswith("/opt") else ("/root", "/root", 0o755)
        )
    found[interpreter] = ("root", "root", 0o755)
    found["/root"] = ("root", "root", 0o700)
    found["/root/.local/share"] = ("root", "root", 0o700)
    return found


def verdict_of(checks: Any, name: str) -> Verdict:
    found: Verdict = next(check.verdict for check in checks if check.name == name)
    return found


def library(root: Path) -> Path:
    """A `library.db` the `library` check can be satisfied by, in `tmp_path`.

    Written by hand rather than by the Builder, for the reason `test_installer_checks.py` gives:
    this file tests a verdict, and a fixture that ran the pipeline would make a Builder change look
    like an installer bug. It lives in `tmp_path` even though the machine being described is a
    production one, because the check takes the path as a parameter and a test must not write to
    `/var/lib`.
    """

    path = root / "library.db"
    with sqlite3.connect(path) as database:
        database.execute("CREATE TABLE songs (id integer primary key, title text)")
        database.executemany(
            "INSERT INTO songs (title) VALUES (?)", [(f"n{i}",) for i in range(12)]
        )
        database.execute("CREATE VIRTUAL TABLE song_search USING fts5(title)")
    return path


def _parents(path: str) -> list[str]:
    parts = PurePath(path).parts
    return [str(PurePath(*parts[: index + 1])) for index in range(len(parts) - 1)]


class _Appliance:
    """An installed machine, answered from tables.

    `FakeMachine` is the wrong double for this bug rather than an inconvenient one: it is a real
    filesystem with a scripted host, so its `/opt/encore` is a temporary directory and its accounts
    are this box's. #46 needs a host whose modes are the ones 13.5 sets and whose service account is
    not the user running pytest.

    Any method this class has not thought about raises, so the next question added to `observe()`
    fails here loudly instead of narrowing this file to whatever #46 happened to need.
    """

    def __init__(self, *, modes: Mapping[str, tuple[str, str, int]], link: str) -> None:
        self._modes: dict[str, tuple[str, str, int]] = dict(modes)
        self._link = link
        self.recorder = RecordingRunner()

    @property
    def commands(self) -> RecordingRunner:
        return self.recorder

    @property
    def environ(self) -> Mapping[str, str]:
        return {"PATH": "/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin"}

    @property
    def running_as_root(self) -> bool:
        return True

    def os_release(self) -> OsRelease:
        return OsRelease(id="debian", pretty_name="Debian GNU/Linux 12 (bookworm)")

    def hostname(self) -> str:
        return "jukebox"

    def which(self, name: str) -> Path | None:
        return {
            "mpv": Path("/usr/bin/mpv"),
            "uv": Path("/home/matt/.local/bin/uv"),
            "rsync": Path("/usr/bin/rsync"),
        }.get(name)

    def user_exists(self, name: str) -> bool:  # noqa: ARG002 - the machine has exactly one account
        return True

    def user(self, name: str) -> ServiceAccount | None:
        # The account 13.5 creates: no login shell, home in the state directory, a primary group of
        # its own. None of that is what #46 turns on, which is the finding.
        return ServiceAccount(
            name=name, shell="/usr/sbin/nologin", home="/var/lib/encore", group=name
        )

    def group_exists(self, name: str) -> bool:  # noqa: ARG002 - every group on it exists
        return True

    def systemd_running(self) -> bool:
        return True

    def service(self, name: str) -> ServiceState:
        return ServiceState(name=name, installed=True, enabled=True, detail="inactive")

    def disk_free(self, path: Path) -> int:  # noqa: ARG002
        return 64 * 1024**3

    def port_free(self, host: str, port: int) -> bool:  # noqa: ARG002
        return True

    def stat(self, path: Path) -> PathState:
        answer = self._modes.get(str(path))
        if answer is None:
            return PathState(path=path)
        owner, group, mode = answer
        return PathState(
            path=path,
            exists=True,
            is_dir=_is_dir(str(path), mode),
            owner=owner,
            group=group,
            mode=mode,
        )

    def resolve(self, path: Path) -> Path:
        # `venv/bin/python`, as `uv` leaves it: a link, not a file. `stat` is an `lstat` everywhere
        # in this installer (a symlink planted at an owned root has to stay visible to `remove`), so
        # following it is a separate question — and the second half of why a mode check never saw
        # #46 coming.
        return Path(self._link) if str(path) == "/opt/encore/venv/bin/python" else path

    def read(self, path: str | Path) -> str | None:
        named = str(path)
        if named.endswith("bin/encore-server"):
            return SHEBANG
        if named.endswith(("uv.lock", ".encore-lock")):
            return LOCK
        if named.endswith("pyproject.toml"):
            return "requires-python = '>=3.12'\n"
        return _RENDERED.get(named)

    def __getattr__(self, name: str) -> Any:
        raise AssertionError(
            f"observe() now asks {name!r}; #46's machine must answer it on purpose"
        )


def _is_dir(named: str, mode: int) -> bool:
    """A table entry with no dot in its last component is a directory here.

    The only question `observe()` asks of `is_dir` is whether a path is a file it might read, and
    every path in this file that matters is spelled out above.
    """

    return "." not in named.rsplit("/", 1)[-1] and bool(mode & 0o100)


def appliance(*, fixed: bool = False) -> _Appliance:
    return _Appliance(
        modes=modes(fixed=fixed), link=FIXED_INTERPRETER if fixed else BROKEN_INTERPRETER
    )


def request(layout: Layout = PRODUCTION, *, command: Command = Command.INSTALL) -> Options:
    return Options(
        command=command,
        layout=layout,
        source=checkout(),
        settings=Settings(music_dir=layout.staged("/opt/music")),
        service=True,
    )


def state_on(machine: _Appliance) -> ApplianceState:
    return observe(
        machine,
        layout=PRODUCTION,
        bind_host="127.0.0.1",
        bind_port=8080,
        source=checkout(),
        http=StubHttpProbe({}),
    )


# -- the command, not the function -------------------------------------------


def test_the_sync_is_told_where_to_put_the_interpreter(tmp_path: Path) -> None:
    """The one argument that would have prevented #46, asserted on a run rather than a function.

    `uv` puts a downloaded CPython in `UV_PYTHON_INSTALL_DIR`, whose default is the invoking
    account's `~/.local/share/uv/python`. Naming it is not enough on its own — uv also searches a
    data directory beside the `uv` binary, which #38 deliberately made the operator's — so the
    appliance installs its own interpreter and then *names* it on the `uv sync` command line. On
    `main` neither command exists.
    """

    machine = FakeMachine(
        recorder=RecordingRunner(effects=synced(), real=(("rsync",),)),
        root=True,
        systemd=True,
        binaries={"mpv": Path("/usr/bin/mpv"), "uv": Path("/home/matt/.local/bin/uv")},
    )
    code = main(
        ["install", "--root", str(tmp_path), "--music-dir", str(tmp_path / "opt" / "music")],
        machine=machine,
        http=StubHttpProbe({}),
    )
    assert code in (EXIT_OK, EXIT_VERIFICATION), code
    transcript = machine.recorder.transcript()
    assert machine.recorder.ran("uv", "python", "install"), (
        "nothing asked for an interpreter, so `uv` picked one wherever it found it — which is #46\n"
        + transcript
    )
    install = machine.recorder.one("uv", "python", "install")
    assert install is not None
    assert "--install-dir" in install.argv
    assert install.argv[install.argv.index("--install-dir") + 1] == str(
        tmp_path / "opt/encore/python"
    ), install.argv
    sync = machine.recorder.one("uv", "sync")
    assert sync is not None, transcript
    assert sync.env is not None
    assert sync.env["UV_PROJECT_ENVIRONMENT"] == str(tmp_path / "opt/encore/venv")
    assert sync.env["UV_PYTHON_INSTALL_DIR"] == str(tmp_path / "opt/encore/python"), (
        "the venv was named and the interpreter was left wherever the invoking account keeps it"
    )
    # The interpreter is passed as well as env-named, because uv searches a data directory beside
    # the `uv` binary too (#38's search path) and demonstrably prefers it over the variable.
    assert "--python" in sync.argv, sync.argv
    named = Path(sync.argv[sync.argv.index("--python") + 1])
    assert named.is_relative_to(tmp_path / "opt/encore/python"), (
        f"the sync named an interpreter outside the appliance: {named}"
    )
    assert named.is_file(), f"the plan named an interpreter that is not there: {named}"


def test_the_rehearsal_leaves_a_venv_that_points_at_the_appliance(tmp_path: Path) -> None:
    """What the fake now builds, because a shell script with no interpreter cannot express #46.

    `synced()` used to write `#!/bin/sh`, so the entry point had no interpreter and the reachability
    question could not be asked of any staged tree — a double that cannot describe the machine. It
    now leaves the chain `uv` leaves: a `bin/python` symlink into the directory the command named.
    """

    machine = FakeMachine(
        recorder=RecordingRunner(effects=synced(), real=(("rsync",),)),
        root=True,
        systemd=True,
        binaries={"mpv": Path("/usr/bin/mpv"), "uv": Path("/usr/local/bin/uv")},
    )
    assert main(
        ["install", "--root", str(tmp_path), "--music-dir", str(tmp_path / "opt" / "music")],
        machine=machine,
        http=StubHttpProbe({}),
    ) in (EXIT_OK, EXIT_VERIFICATION)
    launcher = tmp_path / "opt/encore/venv/bin/python"
    assert launcher.is_symlink()
    reached = launcher.resolve()
    python_dir = tmp_path / "opt/encore/python"
    assert reached.is_file(), reached
    assert python_dir in reached.parents, (
        "the venv's interpreter lives inside the appliance, not in whoever ran the installer"
    )
    assert reached.name == f"python{PYTHON_VERSION}"
    assert ".0-test" in reached.parent.parent.name, (
        "the versioned directory, not uv's stable alias beside it: the alias resolves to the same "
        "file and a report naming it would be naming a symlink"
    )
    assert python_dir.is_dir(), "created with the rest of the layout (SAPRS 13.3)"


# -- what the machine says, and what the installer concludes -----------------


def test_an_installed_appliance_reports_an_interpreter_the_service_cannot_reach() -> None:
    """#46 observed rather than asserted: `observe()` names the directory that stopped the walk.

    The new state fields exist because the fact was not expressible. `environment_runnable` was the
    installer's whole knowledge of the environment, and it is *true* on this machine — that is the
    sentence the report printed while the appliance could not start.
    """

    state = state_on(appliance())
    assert state.environment_runnable, "the entry point is there and executable; that was the bug"
    assert state.environment_matches, "the stamp matches too, so nothing already asked finds this"
    assert state.interpreter == Path(BROKEN_INTERPRETER), state.interpreter
    assert state.interpreter_blocker == Path("/root"), state.interpreter_blocker


def test_that_machine_fails_verification(tmp_path: Path) -> None:
    """The line that was missing from `verify`, on the machine from the report.

    Green with a dead appliance is worse than red with a working one, and the reason it was green is
    that the check asked a file about its mode instead of asking an account about a path. Asked of
    `install` the same fact is a warning, because that run is the repair — see the test below.
    """

    library_db = library(tmp_path)
    checks = assess(
        state_on(appliance()),
        request(command=Command.VERIFY),
        config=EncoreConfig(),
        library_db=library_db,
        runtime_db=tmp_path / "runtime.db",
    )
    environment = next(check for check in checks if check.name == "environment")
    assert environment.verdict is Verdict.FAIL, environment
    assert "encore cannot reach" in environment.detail, environment.detail
    assert "/root" in environment.detail, "name the directory, not the concept"
    assert "/opt/encore/python" in environment.fix, environment.fix


def test_an_install_of_that_machine_is_not_blocked_by_its_own_repair(tmp_path: Path) -> None:
    """#46's second lesson, which #43 taught from the other direction.

    The first version of this check made an unreachable interpreter a *prerequisite* failure, and on
    the real machine that produced an installer refusing to run — `a prerequisite is unmet, so
    nothing was changed` — over the one defect its own run fixes. A finding belongs in `blocked()`
    only when the requested change cannot address it, so what is asserted here is the gate rather
    than the sentence.
    """

    checks = assess(
        state_on(appliance()),
        request(),
        config=EncoreConfig(),
        library_db=library(tmp_path),
        runtime_db=tmp_path / "runtime.db",
    )
    assert not blocked(checks), [check.detail for check in checks if check.blocking]
    assert verdict_of(checks, "environment") is Verdict.WARN


def test_the_repair_is_planned_rather_than_declared_already_done() -> None:
    """The difference between an installer that was fixed and a machine that gets fixed.

    Every existing comparison says the environment is current — and it is, for the root shell that
    built it. An `install` that believed that would print `nothing to do — the machine already
    matches this request` on an appliance that cannot start. Reachability is therefore part of
    "current", not an opinion the plan is free to ignore.
    """

    state = state_on(appliance())
    actions = install_plan(request(), state, EncoreConfig()).actions
    syncs = [action for action in actions if isinstance(action, SyncEnvironment)]
    assert syncs, [action.detail for action in actions]
    assert "reach" in syncs[0].detail, syncs[0].detail


def test_a_reachable_interpreter_plans_no_sync() -> None:
    """The same table, with `/opt/encore/python` at the end of the link instead.

    Without this half the test above could be satisfied by a check that always fails, which is how
    #43's fix nearly became a check that refused every install on a healthy machine.
    """

    actions = install_plan(request(), state_on(appliance(fixed=True)), EncoreConfig()).actions
    assert not [action for action in actions if isinstance(action, SyncEnvironment)], [
        action.detail for action in actions
    ]


def test_a_rehearsal_does_not_diagnose_its_own_temporary_directory(tmp_path: Path) -> None:
    """The guard, pinned: staging asks nothing of `/opt/encore`, so it asks nothing of `User=`.

    Every pytest prefix is `0700` owned by whoever ran pytest, so answering the traversal question
    about a staged tree would report a broken interpreter on every rehearsal in the suite and plan a
    re-sync that never converges. This is #41's `EnsureOwnership` rule arrived at again from the
    other side: a rehearsal is not the machine.
    """

    machine = FakeMachine(root=True, user=True, systemd=True)
    state = observe(
        machine,
        layout=Layout(root=tmp_path),
        bind_host="127.0.0.1",
        bind_port=8080,
        source=checkout(),
        http=StubHttpProbe({}),
    )
    assert state.user_exists, "an account in a rehearsal is a fiction, and this one is scripted"
    assert state.interpreter_blocker is None, state.interpreter_blocker


