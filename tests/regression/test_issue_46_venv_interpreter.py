"""Regression: #46 — an installed appliance whose Python lives where the service cannot walk.

The failure is not in a check or in a plan; it is in what `ExecStart` means.
`/opt/encore/venv/bin/encore-server` is `0755`, its venv is `0755`, and the first line of the file
names an interpreter that is a symlink into `/root/.local/share/uv/python` — because `uv` downloads a
CPython when the distribution has none new enough (Debian 12 ships 3.11, the project requires 3.12)
and puts the download in the home of whoever ran the command: root, under `sudo`, on a machine whose
`/root` is `drwx------`. systemd answers `status=203/EXEC`, and every acceptance line above it says
OK, because a mode check cannot see a traversal problem.

Two things make this file different from `tests/unit/test_installer_system.py`, which already proves
the traversal arithmetic:

* It runs `main()`, so the claim is that a *command* tells `uv` where to put the interpreter rather
  than that a function knows about it. #46 shipped with a `uv sync` that named the venv and nothing
  else.
* It describes an installed appliance at the documented paths, from tables. `FakeMachine` cannot: it
  is a real filesystem with a scripted host, so its `/opt/encore` is a temporary directory under a
  `0700` pytest prefix and its accounts are this box's — which is why `observe()` declines to ask the
  question in a staged run, and why the machine that *is* installed needs its own answers here.

The root-only test is the one nothing can stand in for, and the reason this file exists: the
arithmetic in `interpreter_blocker` re-implements what the kernel does, and only a root process can
ask a *foreign* account whether it can reach a path.
"""

