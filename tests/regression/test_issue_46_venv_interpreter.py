def test_the_kernel_and_the_arithmetic_agree_about_a_foreign_account() -> None:
    """`interpreter_blocker` reimplements `access(2)`, so it is checked against `access(2)`.

    Root only, because the identity that has to be asked about is not the one running the test: a
    process can answer the question about itself, and its answer is the *wrong* one — that is what
    `ok environment` meant on the machine in the report. Only root can make the kernel speak for
    another account.

    A directory a test creates cannot live under `/root`, so this is not #46 literally. What it is:
    a `0700` root-owned directory with a `0755` executable below it, and an account below that is
    neither the owner nor in the group. The arrangement is the bug.
    """

    if os.geteuid() != 0:
        pytest.skip("only a root process can ask the kernel about another account's permissions")
    account = pwd.getpwnam("nobody")
    # Not `tmp_path`, whose parent is `0700`: `nobody` would stop two directories early and the test
    # would be asserting the arithmetic against somebody's temporary tree rather than against the one
    # door it means. `/tmp` itself is `1777`, so a directory made directly in it is reachable up to
    # the point where this test puts the door — which the first version of this test found out by
    # running, correctly, as root.
    prefix = Path(tempfile.mkdtemp(prefix="encore-46-"))
    prefix.chmod(0o755)
    try:
        private = prefix / "home"
        private.mkdir()
        private.chmod(0o700)
        interpreter = private / "python3.12"
        interpreter.write_text("#!/bin/sh\nexit 0\n")
        interpreter.chmod(0o755)

        service = ServiceAccount(name="nobody", shell="/usr/sbin/nologin", home="/nonexistent")
        assert interpreter_blocker(RealMachine(), interpreter, account=service) == private, (
            "the predicate walked somewhere the kernel would not have"
        )

        pid = os.fork()
        if pid == 0:  # pragma: no cover - the child's entire life is three syscalls
            try:
                os.setresgid(account.pw_gid, account.pw_gid, account.pw_gid)
                os.setresuid(account.pw_uid, account.pw_uid, account.pw_uid)
                os.execv(str(interpreter), [str(interpreter)])  # noqa: S606 - no shell is the point
            except OSError:  # pragma: no cover - the expected ending
                os._exit(126)
        _, status = os.waitpid(pid, 0)
        assert not os.WIFEXITED(status) or os.waitstatus_to_exitcode(status) != 0, (
            "the kernel let an account through a 0700 directory; the predicate is wrong"
        )
    finally:
        shutil.rmtree(prefix, ignore_errors=True)
